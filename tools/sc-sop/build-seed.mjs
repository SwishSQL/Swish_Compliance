#!/usr/bin/env node
/**
 * Builds sql/004_sc_sop_review.sql from the Supply Chain SOP review tool
 * (Swish_SC_SOP_Review_Tool.html, process docket v1.0).
 *
 *   node tools/sc-sop/build-seed.mjs <path-to-html>
 *
 * The HTML embeds the whole register as `const D = {...}` on one line:
 * meta, 28 processes, 423 steps, controls/policies/KPIs/reports/approvals,
 * docket-review items and the feedback already in the register. Each is
 * written to its own table; the full record is kept as JSON in `data` so
 * no field from the docket is lost.
 */
import fs from "node:fs";
import path from "node:path";

const src = process.argv[2];
if (!src) {
  console.error("usage: node tools/sc-sop/build-seed.mjs <Swish_SC_SOP_Review_Tool.html>");
  process.exit(1);
}
const line = fs.readFileSync(src, "utf8").split("\n").find((l) => l.startsWith("const D = {"));
if (!line) throw new Error("register data (const D = {...}) not found");
const D = JSON.parse(line.slice(line.indexOf("{"), line.lastIndexOf("}") + 1));

const s = (v) => (v === null || v === undefined || v === "" ? "NULL" : `N'${String(v).replace(/'/g, "''")}'`);
const j = (v) => s(JSON.stringify(v));

const out = [];
out.push(`/*
 * Supply Chain SOP review (process docket v1.0 · As-is 2026 -> To-be 2027).
 * Generated by tools/sc-sop/build-seed.mjs — do not edit by hand.
 */
CREATE TABLE dbo.sc_sop_meta (
  meta_key    NVARCHAR(40)  NOT NULL CONSTRAINT sc_sop_meta_pkey PRIMARY KEY,
  data        NVARCHAR(MAX) NOT NULL
);
CREATE TABLE dbo.sc_sop_processes (
  id          NVARCHAR(10)  NOT NULL CONSTRAINT sc_sop_processes_pkey PRIMARY KEY,
  seq         INT           NOT NULL,
  grp         NVARCHAR(120) NOT NULL,
  name        NVARCHAR(200) NOT NULL,
  lead_dept   NVARCHAR(120) NULL,
  data        NVARCHAR(MAX) NOT NULL
);
CREATE TABLE dbo.sc_sop_steps (
  id          NVARCHAR(16)  NOT NULL CONSTRAINT sc_sop_steps_pkey PRIMARY KEY,
  process_id  NVARCHAR(10)  NOT NULL CONSTRAINT sc_sop_steps_process_fk REFERENCES dbo.sc_sop_processes(id),
  seq         INT           NOT NULL,
  dept        NVARCHAR(120) NULL,
  change_type NVARCHAR(20)  NULL,
  fit         NVARCHAR(20)  NULL,
  data        NVARCHAR(MAX) NOT NULL
);
CREATE INDEX IX_sc_sop_steps_process ON dbo.sc_sop_steps (process_id, seq);
CREATE TABLE dbo.sc_sop_refs (
  id          NVARCHAR(20)  NOT NULL CONSTRAINT sc_sop_refs_pkey PRIMARY KEY,
  ref_type    NVARCHAR(30)  NOT NULL,
  data        NVARCHAR(MAX) NOT NULL
);
CREATE TABLE dbo.sc_sop_feedback (
  id            INT IDENTITY(1,1) NOT NULL CONSTRAINT sc_sop_feedback_pkey PRIMARY KEY,
  ref_code      NVARCHAR(20)  NULL,
  source        NVARCHAR(20)  NOT NULL CONSTRAINT DF_sc_sop_feedback_source DEFAULT N'app',
  user_id       INT           NULL CONSTRAINT sc_sop_feedback_user_fk REFERENCES dbo.users(id),
  reviewer_name NVARCHAR(255) NOT NULL,
  reviewer_dept NVARCHAR(120) NULL,
  reviewer_role NVARCHAR(120) NULL,
  step_ref      NVARCHAR(16)  NOT NULL,
  fb_type       NVARCHAR(60)  NOT NULL,
  comment       NVARCHAR(MAX) NOT NULL,
  proposed      NVARCHAR(MAX) NULL,
  evidence      NVARCHAR(500) NULL,
  status        NVARCHAR(20)  NOT NULL CONSTRAINT DF_sc_sop_feedback_status DEFAULT N'Open',
  response      NVARCHAR(40)  NULL,
  response_note NVARCHAR(MAX) NULL,
  responded_by  INT           NULL CONSTRAINT sc_sop_feedback_responder_fk REFERENCES dbo.users(id),
  responded_at  DATETIMEOFFSET(3) NULL,
  created_at    DATETIMEOFFSET(3) NOT NULL CONSTRAINT DF_sc_sop_feedback_created_at DEFAULT SYSUTCDATETIME()
);
CREATE INDEX IX_sc_sop_feedback_user ON dbo.sc_sop_feedback (user_id, created_at);
CREATE INDEX IX_sc_sop_feedback_step ON dbo.sc_sop_feedback (step_ref);
GO`);

for (const k of ["meta", "polsumm", "phasing", "openitems", "depts", "roles"]) {
  out.push(`INSERT INTO dbo.sc_sop_meta (meta_key, data) VALUES (${s(k)}, ${j(D[k])});`);
}
out.push("GO");

D.procs.forEach((p, i) => {
  out.push(
    `INSERT INTO dbo.sc_sop_processes (id, seq, grp, name, lead_dept, data) VALUES (${s(p.id)}, ${i + 1}, ${s(p.grp)}, ${s(p.name)}, ${s(p.lead)}, ${j(p)});`
  );
});
out.push("GO");

D.steps.forEach((st, i) => {
  out.push(
    `INSERT INTO dbo.sc_sop_steps (id, process_id, seq, dept, change_type, fit, data) VALUES (${s(st.id)}, ${s(st.pa)}, ${i + 1}, ${s(st.dept)}, ${s(st.change)}, ${s(st.fit)}, ${j(st)});`
  );
  if (i % 40 === 39) out.push("GO");
});
out.push("GO");

Object.entries(D.refs).forEach(([id, r], i) => {
  out.push(`INSERT INTO dbo.sc_sop_refs (id, ref_type, data) VALUES (${s(id)}, ${s(r.t)}, ${j(r)});`);
  if (i % 60 === 59) out.push("GO");
});
out.push("GO");

const toDate = (d) => {
  const m = /^(\d{1,2})-([A-Za-z]{3})-(\d{4})$/.exec(d || "");
  if (!m) return "SYSUTCDATETIME()";
  const mon = "JanFebMarAprMayJunJulAugSepOctNovDec".indexOf(m[2]) / 3 + 1;
  return `'${m[3]}-${String(mon).padStart(2, "0")}-${m[1].padStart(2, "0")}T00:00:00+03:00'`;
};
for (const f of D.fb) {
  out.push(
    `INSERT INTO dbo.sc_sop_feedback (ref_code, source, reviewer_name, reviewer_dept, reviewer_role, step_ref, fb_type, comment, status, response, response_note, created_at) VALUES (${s(f.fid)}, N'register', ${s(f.name)}, ${s(f.dept)}, ${s(f.role)}, ${s(f.step)}, ${s(f.type)}, ${s(f.comment)}, ${s(f.status || "Open")}, ${s(f.resp)}, ${s(f.note)}, ${toDate(f.date)});`
  );
}
out.push("GO", "");

const dest = path.join(path.dirname(new URL(import.meta.url).pathname.replace(/^\/(\w:)/, "$1")), "../../sql/004_sc_sop_review.sql");
fs.writeFileSync(dest, out.join("\n"), "utf8");
console.log(`wrote ${dest}: ${D.procs.length} processes, ${D.steps.length} steps, ${Object.keys(D.refs).length} refs, ${D.fb.length} feedback`);
